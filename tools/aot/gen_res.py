#!/usr/bin/env python3
"""JET AOT resources: bundle (layout XML + values.xml from the JET extractor) -> C tables for the native kernel.

Emits (see Runtime/jetrt.h):
  jet_layouts[]    per layout: nodes (depth, class tag, id, text, contentDescription, attrs)
                   attrs = flat "name","value",... list with the node's style chain flattened (explicit attributes win)
                   and every @ref resolved to a literal: colors "#AARRGGBB", dimens "12.0dip|sp|px", strings, drawables
                   "@d:0x7f030001" (kept symbolic; see jet_drawables)
  jet_strings[]    app strings (for setText(int))
  jet_drawables[]  drawables reachable from the layouts/styles/theme: solid colors / shapes, and selectors as
                   (required-state mask, required-state values, child drawable) rows
  jet_theme_*      window background and default text color of the launcher theme
Generic: nothing here knows about a particular app. Usage: gen_res.py <bundle-dir> <out.c>
"""
import sys, os, re, xml.etree.ElementTree as ET

bundle, out = sys.argv[1], sys.argv[2]
A = '{http://schemas.android.com/apk/res/android}'
VX = open(os.path.join(bundle, 'values.xml'), encoding='utf-8').read()
props = dict(l.rstrip('\n').split('=', 1) for l in open(os.path.join(bundle, 'app.properties'), encoding='utf-8') if '=' in l)

def unesc(s):
    return s.replace('&lt;', '<').replace('&gt;', '>').replace('&quot;', '"').replace('&apos;', "'").replace('&amp;', '&')

values = {}     # id -> (type, value)
for m in re.finditer(r'<value id="0x([0-9a-f]+)" type="([a-z]+)" name="[^"]*" value="([^"]*)"', VX):
    values[int(m.group(1), 16)] = (m.group(2), unesc(m.group(3)))
styles = {}     # id -> (parent, [(name, value)])
for m in re.finditer(r'<style id="0x([0-9a-f]+)" name="[^"]*" parent="0x([0-9a-f]+)">(.*?)</style>', VX, re.S):
    items = [(n, unesc(v)) for n, v in re.findall(r'<item name="([^"]*)" value="([^"]*)"/>', m.group(3))]
    styles[int(m.group(1), 16)] = (int(m.group(2), 16), items)
drawables = {}  # id -> attrs dict + states
for m in re.finditer(r'<drawable id="0x([0-9a-f]+)"((?:[^>/]|/(?!>))*)(?:/>|>(.*?)</drawable>)', VX, re.S):
    d = dict(re.findall(r'(\w+)="([^"]*)"', m.group(2)))
    d['states'] = re.findall(r'<state when="([^"]*)" drawable="([^"]*)"/>', m.group(3) or '')
    drawables[int(m.group(1), 16)] = d

def refid(v):
    """'@7F010000' / '@android:0106000E' / '@0x...' -> int id, else None"""
    if not v or not v.startswith('@'): return None
    h = v[1:].split(':')[-1]
    if h.startswith('0x'): h = h[2:]
    try: return int(h, 16)
    except ValueError: return None

def color(v, depth=0):
    if v is None or depth > 8: return None
    if v.startswith('#'):
        h = v[1:]
        if len(h) == 3: h = ''.join(c * 2 for c in h)
        if len(h) == 4: h = ''.join(c * 2 for c in h)
        if len(h) == 6: h = 'FF' + h
        return '#' + h.upper()
    r = refid(v)
    if r is not None and r in values and values[r][0] == 'color': return color(values[r][1], depth + 1)
    return None

def resolve(name, v, depth=0):
    """attribute value -> literal string for the C kernel"""
    if v is None or depth > 8: return v
    r = refid(v)
    if r is None: return v
    if r in drawables:
        need_drawable(r); return '@d:0x%08x' % r
    if r in values:
        t, val = values[r]
        if t == 'color':
            c = color(val)
            if c: return c
        return resolve(name, val, depth + 1)
    return v

needed = set()
def need_drawable(r, depth=0):
    if r in needed or depth > 8 or r not in drawables: return
    needed.add(r)
    for _, ch in drawables[r]['states']:
        c = refid(ch)
        if c is not None and c in drawables: need_drawable(c, depth + 1)

def style_items(sid, depth=0):
    if not sid or sid not in styles or depth > 16: return []
    parent, items = styles[sid]
    return style_items(parent, depth + 1) + items   # child items override parent (later wins)

def cstr(s):
    if s is None: return 'NULL'
    return '"' + ''.join(c if (32 <= ord(c) < 127 and c not in '"\\?') else ''.join('\\%03o' % b for b in c.encode()) for c in s) + '"'

L = ['/* generated by tools/aot/gen_res.py from the JET bundle of %s — do not edit */' % props.get('package', '?'), '#include "jetrt.h"']
lays = []
for f in sorted(os.listdir(os.path.join(bundle, 'layout'))):
    lid = int(f.split('.')[0], 16)
    root = ET.parse(os.path.join(bundle, 'layout', f)).getroot()
    nodes, attrdefs = [], []
    def walk(e, d):
        at = {}
        st = e.get('style')
        sid = refid(st) if st else None
        for n, v in style_items(sid): at[n.split(':')[-1]] = v
        for k, v in e.attrib.items():
            if k.startswith(A): at[k[len(A):]] = v
        flat = []
        for k in sorted(at):
            if k in ('id', 'style'): continue
            rv = resolve(k, at[k])
            if rv is not None: flat += [k, rv]
        an = 'at_%x_%d' % (lid, len(nodes))
        attrdefs.append('static const char *const %s[] = {%s};' % (an, ','.join([cstr(x) for x in flat] + ['NULL'])))
        text = resolve('text', at.get('text')) if 'text' in at else None
        desc = resolve('contentDescription', at.get('contentDescription')) if 'contentDescription' in at else None
        nodes.append('{%d,%s,%d,%s,%s,%s}' % (d, cstr(e.tag), refid(e.get(A + 'id')) or 0, cstr(text), cstr(desc), an))
        for c in e: walk(c, d + 1)
    walk(root, 0)
    L += attrdefs
    L.append('static const JResNode lay_%x[] = {%s, {-1,NULL,0,NULL,NULL,NULL}};' % (lid, ','.join(nodes)))
    lays.append(lid)
L.append('const JResLayout jet_layouts[] = {%s{0,NULL}};' % ''.join('{%d,lay_%x},' % (l, l) for l in lays))
L.append('const JResString jet_strings[] = {%s{0,NULL}};' % ''.join('{%d,%s},' % (k, cstr(v)) for k, (t, v) in sorted(values.items()) if t == 'string' and k >> 24 == 0x7f))

# theme: window background + default text color, following the parent chain of the launcher/app theme
def theme_attr(name):
    tid = refid(props.get('mainActivityTheme') or '') or refid(props.get('appTheme') or '')
    for n, v in reversed(style_items(tid)):
        if n.split(':')[-1] == name: return v
    return None
STATE = {'state_pressed': 1, 'state_selected': 2, 'state_focused': 4, 'state_enabled': 8, 'state_checked': 16,
         'state_window_focused': 32, 'state_accelerated': 64, 'state_activated': 128, 'state_hovered': 256}
wbg = theme_attr('windowBackground'); wid = refid(wbg) if wbg else None
if wid is not None: need_drawable(wid)
tcol = color(theme_attr('textColorPrimary') or '') or None
# textColorPrimary is usually a color state list file; fall back to its default (light/dark from colorBackground)
if tcol is None:
    bgc = color(theme_attr('colorBackground') or '') or '#FF000000'
    lum = int(bgc[3:5], 16) + int(bgc[5:7], 16) + int(bgc[7:9], 16)
    tcol = '#FF000000' if lum > 384 else '#FFFFFFFF'

rows = []
for r in sorted(needed):
    d = drawables[r]; kind = d.get('kind'); col = 0; states = []
    if kind in ('shape', 'color'):
        c = color(d.get('solid') or d.get('value') or d.get('color') or d.get('g_startColor') or '')
        if c: kind, col = 1, int(c[1:], 16)
        else: kind = 0
    elif kind == 'selector':
        for when, ch in d['states']:
            mask = val = 0
            for tok in [t for t in when.split(',') if t]:
                neg = tok.startswith('!'); tok = tok.lstrip('!')
                bit = STATE.get(tok)
                if bit is None: mask = -1; break     # unknown state: row can never match
                mask |= bit; val |= 0 if neg else bit
            if mask < 0: continue
            c = refid(ch); cc = color(ch) if c is None or c not in drawables else None
            if cc:  # inline color item
                rows.append('{0x%08x,3,0x%s,NULL}' % (0x7e000000 | len(rows), cc[1:])); child = 0x7e000000 | (len(rows) - 1)
            else: child = c or 0
            states += [mask, val, child]
        kind = 2
    else:
        kind = 0   # bitmap / ninepatch / vector / layer-list: drawn as nothing in this kernel version
    sn = 'NULL'
    if states:
        sn = 'ds_%x' % r
        L.append('static const int32_t %s[] = {%s, -1};' % (sn, ','.join('(int32_t) 0x%08x' % (x & 0xffffffff) for x in states)))
    rows.append('{0x%08x,%d,0x%08xu,%s}' % (r, kind, col, sn))
L.append('const JResDrawable jet_drawables[] = {%s{0,0,0,NULL}};' % ''.join(x + ',' for x in rows))
L.append('const int32_t jet_theme_window_bg = (int32_t) 0x%08x;' % ((wid or 0) & 0xffffffff))
L.append('const uint32_t jet_theme_text_color = 0x%su;' % tcol[1:])
open(out, 'w').write('\n'.join(L) + '\n')
print('gen_res: layouts %d, strings %d, drawables %d, theme bg %s text %s' % (len(lays), sum(1 for t, _ in values.values() if t == 'string'), len(rows), hex(wid or 0), tcol))
