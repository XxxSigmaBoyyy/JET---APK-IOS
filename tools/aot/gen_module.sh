#!/usr/bin/env bash
# Regenerate an AOT app module (Modules/<name>/) from an OPEN-SOURCE APK with the JET toolchain in tools/aot.
#
#   tools/aot/gen_module.sh --name heading --apk APK --jar JAR --bundle BUNDLE_DIR [--soot DIR]
#
#   APK     the open-source APK (used only for its classes.dex CRC-32; never copied into the repo)
#   JAR     the APK's classes converted to a jar (dex2jar / the JET harness cache)
#   BUNDLE  the JET bundle extracted from the APK (app.properties + values.xml + layouts)
#   --soot  directory with soot.jar and platforms/android-33/android.jar (default: $JET_SOOT or ../proto/tools/soot)
#
# Output: Modules/<name>/<name>_app.c (Jimple -> C, jet.aot.JimpleToC), <name>_res.c (tools/aot/gen_res.py),
# jet_module.c (metadata). Only modules generated from open-source apps whose licence allows redistribution may be
# committed; add a NOTICE in the module directory. Closed-source output must never be committed.
set -euo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
NAME=""; APK=""; JAR=""; BUNDLE=""; SOOTDIR="${JET_SOOT:-$REPO/../proto/tools/soot}"
while [ $# -gt 0 ]; do
  case "$1" in
    --name) NAME="$2"; shift 2 ;; --apk) APK="$2"; shift 2 ;; --jar) JAR="$2"; shift 2 ;;
    --bundle) BUNDLE="$2"; shift 2 ;; --soot) SOOTDIR="$2"; shift 2 ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;; *) echo "gen_module: unknown argument $1" >&2; exit 2 ;;
  esac
done
[[ "$NAME" =~ ^[A-Za-z0-9_]+$ ]] || { echo "gen_module: --name must be [A-Za-z0-9_]+" >&2; exit 2; }
for f in "$APK" "$JAR" "$BUNDLE/app.properties" "$SOOTDIR/soot.jar" "$SOOTDIR/platforms/android-33/android.jar"; do
  [ -f "$f" ] || { echo "gen_module: missing $f" >&2; exit 2; }
done
case "$(cd "$(dirname "$APK")" && pwd)/" in */apks_closed/*) echo "gen_module: refusing closed APK $APK" >&2; exit 2 ;; esac
OUT="$REPO/Modules/$NAME"; TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT; mkdir -p "$OUT"
javac -nowarn -cp "$SOOTDIR/soot.jar" -d "$TMP" "$REPO"/tools/aot/src/jet/aot/*.java 2>&1 | grep -v '^Note' || true
java -cp "$SOOTDIR/soot.jar:$TMP" jet.aot.JimpleToC "$JAR" "$SOOTDIR/platforms/android-33/android.jar" "$OUT/${NAME}_app.c" 2>&1 | grep -v 'SLF4J\|^\[main\]' || true
[ -s "$OUT/${NAME}_app.c" ] || { echo "gen_module: JimpleToC produced no output" >&2; exit 1; }
python3 "$REPO/tools/aot/gen_res.py" "$BUNDLE" "$OUT/${NAME}_res.c"
python3 - "$APK" "$BUNDLE/app.properties" "$NAME" "$OUT/jet_module.c" <<'PY'
import sys, zipfile
apk, props, name, out = sys.argv[1:]
p = dict(l.rstrip("\n").split("=", 1) for l in open(props, encoding="utf-8") if "=" in l)
crc = zipfile.ZipFile(apk).getinfo("classes.dex").CRC
def c(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
open(out, "w").write(f"""/* generated by tools/aot/gen_module.sh — AOT module metadata */
#include <stdint.h>
const int jet_mod_present = 1;
const char jet_mod_name[] = {c(name)}, jet_mod_package[] = {c(p["package"])}, jet_mod_activity[] = {c(p["mainActivity"])}, jet_mod_label[] = {c(p.get("label", name))};
const uint32_t jet_mod_dexcrc = 0x{crc:08x}u;
""")
print(f"gen_module: {name}: {p['package']} / {p['mainActivity']} dex crc {crc:08x}")
PY
# strip build-host paths from generated comments
sed -i.bak "s#$REPO/##g; s#$(dirname "$REPO")/##g" "$OUT"/*.c && rm -f "$OUT"/*.bak
wc -l "$OUT"/*.c
